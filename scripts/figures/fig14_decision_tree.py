#!/usr/bin/env python3
"""Write media/fig-14-anc-hiv-decision-tree.svg: Fig. 14 of the PHC handbook (the WHO ANC
DAK decision tree for provider-initiated HIV testing and counselling at antenatal
registration), drawn from the data below in the figure's own words.

Every box, line and arrow of the figure is in NODES and EDGES; the words come from
who-iris vector-labels.json, PDF page 46. Re-run to regenerate.
"""
import json, sys
from xml.sax.saxutils import escape as esc

OUT = sys.argv[1] if len(sys.argv) > 1 else "folio/dth-phc/media/fig-14-anc-hiv-decision-tree.svg"
DATA = sys.argv[2] if len(sys.argv) > 2 else "folio/dth-phc/media/fig-14-anc-hiv-decision-tree.json"
ORANGE, PURPLE, INK = "#E8A33D", "#A0338E", "#1A1A1A"

# id: (x, y, w, h, colour, title lines, body lines, body style)
NODES = {
 "registration": (70, 20, 820, 64, "fill", ["Antenatal registration"], ["Provider-initiated HIV testing & counselling"], "plain"),
 "hiv-positive": (40, 120, 330, 72, PURPLE, ["HIV-positive"], ["PMTCT, treatment, support,", "offer partner notification"], "italic"),
 "hiv-negative": (400, 120, 520, 72, ORANGE, ["HIV-negative"], ["Standard HIV post-test guidance and", "counselling on prevention"], "italic"),
 "partner-testing": (40, 240, 330, 50, PURPLE, ["Partner testing"], [], "plain"),
 "offer-partner-testing": (400, 226, 240, 72, ORANGE, ["Offer partner testing", "& conduct risk", "assessment"], [], "plain"),
 "risk-assessment": (660, 226, 260, 50, ORANGE, ["Risk assessment", "using tool"], [], "plain"),
 "partner-hiv-negative": (40, 340, 140, 82, ORANGE, ["Partner", "HIV-", "negative"], [], "plain"),
 "partner-not-tested": (190, 340, 180, 270, PURPLE, ["Partner not", "tested or", "HIV-positive"], ["Offer partner:", "1. HIV treatment", "    (if HIV-positive)", "2. Condom", "    promotion", "3. Risk reduction", "    counselling"], "italic"),
 "partner-negative-actions": (40, 440, 140, 170, ORANGE, [], ["» Reassess", "   woman’s", "   risk", "» Offer", "   partner", "   referral for", "   VMMC"], "italic"),
 "at-risk": (400, 340, 240, 72, ORANGE, ["Woman at", "substantial risk of", "HIV acquisition"], [], "plain"),
 "not-at-risk": (660, 340, 260, 72, ORANGE, ["Woman not at", "substantial risk of", "HIV acquisition"], [], "plain"),
 "prevention-options": (400, 446, 520, 170, ORANGE, ["Provide comprehensive HIV prevention options:"], ["1. STI screening and treatment (syndromic and syphilis)", "2. Condom promotion", "3. Risk reduction counselling", "4. PrEP with emphasis on adherence", "5. Emphasize importance of follow-up ANC visits"], "italic"),
 "initiate-prep": (400, 640, 520, 120, ORANGE, ["Woman who chooses to initiate PrEP"], ["1. Clinical laboratory assessments", "2. Adherence counselling", "3. Emphasize importance of follow-up visits and repeat", "    HIV testing"], "italic"),
}
EDGES = [("registration", "hiv-positive"), ("registration", "hiv-negative"), ("hiv-positive", "partner-testing"),
         ("hiv-negative", "offer-partner-testing"), ("hiv-negative", "risk-assessment"), ("offer-partner-testing", "partner-testing"),
         ("partner-testing", "partner-hiv-negative"), ("partner-testing", "partner-not-tested"),
         ("risk-assessment", "at-risk"), ("risk-assessment", "not-at-risk"), ("at-risk", "prevention-options"),
         ("prevention-options", "initiate-prep")]
FOOT = ["ANC: antenatal care; PMTCT: prevention of mother-to-child transmission; PrEP: pre-exposure prophylaxis; STI: sexually",
        "transmitted infection; VMMC: voluntary medical male circumcision.", "Source: WHO (29)"]
W, H = 960, 840

def cx(n): x, y, w, h, *_ = NODES[n]; return x + w / 2
def top(n): return NODES[n][1]
def bot(n): x, y, w, h, *_ = NODES[n]; return y + h

out = [f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/figures/fig14_decision_tree.py from {DATA.split("/")[-1]} — do not edit; re-run the script. -->\n',
       f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" font-family="\'Open Sans\',\'Segoe UI\',Helvetica,Arial,sans-serif" font-size="15" role="img" aria-labelledby="t">\n',
       '<title id="t">Fig. 14. Decision-support logic for a clinical care pathway in the form of a decision tree</title>\n',
       f'<defs><marker id="arr" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0 0L10 5L0 10Z" fill="{INK}"/></marker></defs>\n',
       f'<rect width="{W}" height="{H}" fill="#E6E7E8"/>\n']
# edges: dotted, right-angled (down from the source, across, down into the target); one sideways
for a, b in EDGES:
    if (a, b) == ("offer-partner-testing", "partner-testing"):
        y = top(b) + 25
        out.append(f'<path d="M{NODES[a][0]} {y}H{NODES[b][0] + NODES[b][2] + 2}" fill="none" stroke="{INK}" stroke-width="1.6" stroke-dasharray="2 3" marker-end="url(#arr)"/>\n')
        continue
    y0, y1 = bot(a), top(b)
    mid = y0 + max(10, (y1 - y0) / 2)
    out.append(f'<path d="M{cx(a)} {y0}V{mid}H{cx(b)}V{y1 - 2}" fill="none" stroke="{INK}" stroke-width="1.6" stroke-dasharray="2 3" marker-end="url(#arr)"/>\n')
for n, (x, y, w, h, colour, title, body, style) in NODES.items():
    fill = ORANGE if colour == "fill" else "#FFFFFF"
    stroke = ORANGE if colour == "fill" else colour
    out.append(f'<g id="{n}"><rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}" stroke="{stroke}" stroke-width="2"/>\n')
    ty = y + 22
    for i, t in enumerate(title):
        colour_t = colour if n in ("hiv-positive", "hiv-negative") else INK
        out.append(f'<text x="{x + w / 2}" y="{ty}" text-anchor="middle" font-weight="700" font-size="17" fill="{colour_t}">{esc(t)}</text>\n')
        ty += 20
    anchor_mid = n in ("registration", "hiv-positive", "hiv-negative")
    for t in body:
        attrs = ' font-style="italic"' if style == "italic" else ""
        if anchor_mid: out.append(f'<text x="{x + w / 2}" y="{ty}" text-anchor="middle"{attrs}>{esc(t)}</text>\n')
        else: out.append(f'<text x="{x + 10}" y="{ty}" xml:space="preserve"{attrs}>{esc(t)}</text>\n')
        ty += 19
    out.append('</g>\n')
for i, t in enumerate(FOOT):
    out.append(f'<text x="20" y="{790 + i * 18}" font-size="12">{esc(t)}</text>\n')
out.append('</svg>\n')
open(OUT, "w").write("".join(out))
json.dump({"$comment": "Fig. 14 as data: boxes in the figure's words, and the arrows between them. Written by scripts/figures/fig14_decision_tree.py.",
           "figure": "Fig. 14", "source": "who-iris/library/9789240093362-eng, PDF page 46",
           "nodes": [{"id": n, "title": " ".join(v[5]), "text": [l.strip() for l in v[6]]} for n, v in NODES.items()],
           "edges": [{"from": a, "to": b} for a, b in EDGES], "footnote": FOOT}, open(DATA, "w"), indent=1, ensure_ascii=False)
print("wrote", OUT, DATA)
