#!/usr/bin/env python3
"""Write folio/dth-phc/media/fig-4-collect-once.svg: Fig. 4 of the PHC handbook
("The added value of 'collect once, use for many purposes' principle"), drawn from
figure-data/fig-4-collect-once.json.

Five stacked layers, bottom to top; each layer's chevron points up into the layer it
feeds. Words are the figure's own (PDF page 19). Labels that name a glossary concept
link to the term.

Usage: fig4_collect_once.py [--check]
"""
import json
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "figure-data/fig-4-collect-once.json"
OUT = ROOT / "folio/dth-phc/media/fig-4-collect-once.svg"
FONT = "'Source Sans Pro','Source Sans 3','Open Sans','Segoe UI',Helvetica,Arial,sans-serif"
INK, PAGE = "#1A1A1A", "#E6E7E8"
W, TOP, LH_LAYER = 450, 22, 148
BAR_X, BAR_W, CH_X, BOX_X, BOX_R = 25, 143, 62, 168, 420


def esc(s: str) -> str:
    return escape(s, {'"': "&quot;"})


def draw(d: dict) -> str:
    layers = d["layers"]
    n = len(layers)
    bottom = TOP + n * LH_LAYER

    def ytop(i: int) -> float:          # i = 0 is the bottom layer
        return bottom - (i + 1) * LH_LAYER

    out = []
    a = out.append
    # group bars, behind everything
    index = {l["id"]: i for i, l in enumerate(layers)}
    for g in d["groups"]:
        ids = [index[x] for x in g["layers"]]
        y0, y1 = ytop(max(ids)), ytop(min(ids)) + LH_LAYER
        a(f'<g id="group-{g["id"]}"><rect x="{BAR_X}" y="{y0}" width="{BAR_W}" height="{y1 - y0}" fill="{g["colour"]}"/>'
          f'<text transform="translate({BAR_X + 24} {(y0 + y1) / 2}) rotate(-90)" text-anchor="middle" font-weight="700" '
          f'font-size="21" fill="#FFFFFF">{esc(g["label"])}</text></g>\n')
    # chevrons, top layer first so each lower chevron's point lies over the layer above
    peak = 26
    for i in reversed(range(n)):
        l = layers[i]
        yt, yb = ytop(i), ytop(i) + LH_LAYER
        mid = (CH_X + BOX_X) / 2
        if i == n - 1:
            pts = f"{CH_X},{yb} {CH_X},{yt} {BOX_X},{yt} {BOX_X},{yb}"
        else:
            pts = f"{CH_X},{yb} {CH_X},{yt + peak} {mid},{yt - peak} {BOX_X},{yt + peak} {BOX_X},{yb}"
        a(f'<polygon points="{pts}" fill="{l["chevron"]}"/>\n')
    # the person at the bottom layer
    for i, l in enumerate(layers):
        if l.get("person"):
            yt = ytop(i)
            cx = (CH_X + BOX_X) / 2 + 6
            a(f'<g id="person" fill="#DDE9CF"><circle cx="{cx}" cy="{yt + 50}" r="27"/>'
              f'<rect x="{cx - 40}" y="{yt + 84}" width="80" height="{LH_LAYER - 84}" rx="18"/></g>\n')
    # the layer boxes and their words
    for i, l in enumerate(layers):
        yt = ytop(i)
        colour = "#FFFFFF" if l.get("light") else INK
        sub = "#FFFFFF" if l.get("light") else INK
        lines = [(t, True) for t in l["title"]] + [(t, False) for t in l["items"]]
        y = yt + LH_LAYER / 2 - (len(lines) - 1) * 10 + 5
        a(f'<g id="layer-{l["id"]}"><rect x="{BOX_X}" y="{yt}" width="{BOX_R - BOX_X}" height="{LH_LAYER}" fill="{l["fill"]}"/>\n')
        for t, bold in lines:
            weight = ' font-weight="700"' if bold else ""
            text = f'<text x="{(BOX_X + BOX_R) / 2}" y="{y}" text-anchor="middle" font-size="15"{weight} fill="{colour if bold else sub}">{esc(t)}</text>'
            href = l.get("links", {}).get(t)
            a((f'<a href="{esc(href)}">{text}</a>' if href else text) + "\n")
            y += 20
        a("</g>\n")
        if i:
            a(f'<path d="M{BOX_X} {yt + LH_LAYER}H{BOX_R}" stroke="#FFFFFF" stroke-width="1"/>\n')
    a(f'<text x="{BOX_R}" y="{bottom + 34}" text-anchor="end" font-size="14" fill="{INK}">{esc(d["note"])}</text>\n')
    height = bottom + 50
    head = [
        '<?xml version="1.0" encoding="UTF-8"?>\n',
        "<!-- Generated by scripts/figures/fig4_collect_once.py from figure-data/fig-4-collect-once.json. "
        "Do not edit; re-run the script. -->\n",
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {height}" width="{W}" height="{height}" '
        f'font-family="{FONT}" role="img" aria-labelledby="t">\n',
        f'<title id="t">{esc(d["title"])}</title>\n',
        f'<rect width="{W}" height="{height}" fill="{PAGE}"/>\n',
    ]
    return "".join(head + out) + "</svg>\n"


def main() -> None:
    svg = draw(json.loads(DATA.read_text(encoding="utf-8")))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != svg:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run scripts/figures/fig4_collect_once.py")
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.write_text(svg, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
