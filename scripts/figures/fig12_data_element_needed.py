#!/usr/bin/env python3
"""Write folio/dth-phc/media/fig-12-data-element-needed.svg: Fig. 12 of the PHC handbook
("Is each and every data element collected truly needed?"), drawn from the Fig. 12 table
block folio/dth-phc/ch03-user-requirements/t-ch03-fig-12.md, so the words have one source.

Each row is a question, its explanation and the action to be taken, joined by arrows; each
action leads on to the next question, as on PDF page 42.

Usage: fig12_data_element_needed.py [--check]
"""
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "folio/dth-phc/ch03-user-requirements/t-ch03-fig-12.md"
OUT = ROOT / "folio/dth-phc/media/fig-12-data-element-needed.svg"
FONT = "'Source Sans Pro','Source Sans 3','Open Sans','Segoe UI',Helvetica,Arial,sans-serif"
BLUE, NAVY, PURPLE, LAVENDER, INK, PAGE = "#0B8FD2", "#1B2A55", "#5B2C83", "#E6E0EE", "#1A1A1A", "#E6E7E8"
DATA_ELEMENT = "https://litlfred.github.io/dth-phc/v0/ns/glossary/dth-phc/data-element"
W = 954
COLS = [(34, 230), (291, 546), (603, 916)]   # x0, x1 of question, explanation, action


def esc(s: str) -> str:
    return escape(s, {'"': "&quot;"})


def read_table() -> tuple[list[str], list[list[str]]]:
    lines = [l for l in TABLE.read_text(encoding="utf-8").splitlines() if l.startswith("|")]
    split = lambda l: [c.strip() for c in l.strip().strip("|").split(" | ")]
    header = split(lines[0])
    rows = [[re.sub(r"\*\*(.*)\*\*", r"\1", c) for c in split(l)] for l in lines[2:]]
    return header, rows


def wrap(text: str, width: float, size: float) -> list[str]:
    limit = max(8, int(width / (0.52 * size)))
    out, cur = [], ""
    for word in text.split():
        if cur and len(cur) + 1 + len(word) > limit:
            out.append(cur)
            cur = word
        else:
            cur = f"{cur} {word}" if cur else word
    return out + ([cur] if cur else [])


def draw() -> str:
    header, rows = read_table()
    out = []
    a = out.append
    head_colours = [BLUE, NAVY, PURPLE]
    for (x0, x1), h, c in zip(COLS, header, head_colours):
        a(f'<text x="{(x0 + x1) / 2}" y="56" text-anchor="middle" font-weight="700" font-size="22" fill="{c}">{esc(h)}</text>\n')
    y = 76
    gap = 52
    prev_action = None
    for r, (question, explanation, action) in enumerate(rows):
        m = re.match(r"(\d+\.)\s*(.*)", question)
        num, qtext = (m.group(1), m.group(2)) if m else ("", question)
        q_lines = [num] + wrap(qtext, COLS[0][1] - COLS[0][0] - 20, 21)
        e_lines = wrap(explanation, COLS[1][1] - COLS[1][0] - 30, 15.5)
        x_lines = wrap(action, COLS[2][1] - COLS[2][0] - 30, 15.5)
        h = max(len(q_lines) * 26 + 30, len(e_lines) * 20 + 30, len(x_lines) * 20 + 30)
        a(f'<g id="question-{r + 1}">\n')
        if prev_action is not None:                  # the previous action leads on to this question
            px, py = prev_action
            qx = COLS[0][0] + 66
            a(f'<path d="M{px} {py}V{py + gap / 2}H{qx}V{y - 3}" fill="none" stroke="{BLUE}" stroke-width="4" marker-end="url(#arrow)"/>\n')
        (q0, q1), (e0, e1), (x0, x1) = COLS
        a(f'<rect x="{q0}" y="{y}" width="{q1 - q0}" height="{h}" fill="{BLUE}"/>\n')
        ty = y + h / 2 - (len(q_lines) - 1) * 13 + 7
        for t in q_lines:
            words = esc(t).replace("data element", f'<a href="{DATA_ELEMENT}">data element</a>')
            a(f'<text x="{(q0 + q1) / 2}" y="{ty}" text-anchor="middle" font-size="21" fill="#FFFFFF"'
              f'{" font-weight=\"700\"" if t == num else ""}>{words}</text>\n')
            ty += 26
        a(f'<rect x="{e0}" y="{y + 4}" width="{e1 - e0}" height="{h - 8}" fill="#FFFFFF" stroke="{BLUE}" stroke-width="2"/>\n')
        ty = y + h / 2 - (len(e_lines) - 1) * 10 + 5
        for t in e_lines:
            a(f'<text x="{e0 + 16}" y="{ty}" font-size="15.5" fill="{NAVY}">{esc(t)}</text>\n')
            ty += 20
        a(f'<rect x="{x0}" y="{y}" width="{x1 - x0}" height="{h}" fill="{LAVENDER}" stroke="{PURPLE}" stroke-width="2"/>\n')
        ty = y + h / 2 - (len(x_lines) - 1) * 10 + 5
        for t in x_lines:
            a(f'<text x="{x0 + 16}" y="{ty}" font-size="15.5" fill="{PURPLE}">{esc(t)}</text>\n')
            ty += 20
        mid = y + h / 2
        a(f'<path d="M{q1 + 8} {mid}H{e0 - 6}" stroke="{BLUE}" stroke-width="4" marker-end="url(#arrow)"/>\n')
        a(f'<path d="M{e1 + 8} {mid}H{x0 - 6}" stroke="{BLUE}" stroke-width="4" marker-end="url(#arrow)"/>\n')
        a("</g>\n")
        prev_action = ((x0 + x1) / 2 + 90, y + h)
        y += h + gap
    height = y - gap + 30
    head = [
        '<?xml version="1.0" encoding="UTF-8"?>\n',
        "<!-- Generated by scripts/figures/fig12_data_element_needed.py from "
        "folio/dth-phc/ch03-user-requirements/t-ch03-fig-12.md. Do not edit; re-run the script. -->\n",
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {height}" width="{W}" height="{height}" '
        f'font-family="{FONT}" role="img" aria-labelledby="t">\n',
        '<title id="t">Fig. 12. Is each and every data element collected truly needed?</title>\n',
        f'<defs><marker id="arrow" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="4" markerHeight="4" orient="auto">'
        f'<path d="M0 0L10 5L0 10Z" fill="{BLUE}"/></marker></defs>\n',
        f'<rect width="{W}" height="{height}" fill="{PAGE}"/>\n',
    ]
    return "".join(head + out) + "</svg>\n"


def main() -> None:
    svg = draw()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != svg:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run scripts/figures/fig12_data_element_needed.py")
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.write_text(svg, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
